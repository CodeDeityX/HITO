'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const entry=require('../phase0/cli/product-entry.cjs');
const {render}=require('../phase0/cli/human-output.cjs');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'hito-r9b-r2-'));
const project=path.join(temp,'project');fs.mkdirSync(project);
fs.writeFileSync(path.join(project,'README.md'),'# R9B-R2\n','utf8');
fs.writeFileSync(path.join(project,'package.json'),'{}\n','utf8');
fs.writeFileSync(path.join(project,'index.js'),'console.log(1)\n','utf8');
(async()=>{
 await entry.execute('init',{explicit:'.',cwd:project});
 await entry.execute('intake',{explicit:'.',cwd:project});
 fs.writeFileSync(path.join(project,'package.json'),' {"changed":true}\n','utf8');
 const result=await entry.execute('story',{explicit:'.',cwd:project});
 const human=render('story',result,'TEXT');
 const json=JSON.parse(render('story',result,'JSON'));
 assert.deepEqual(result.truth.refresh.changed,['package.json']);
 assert.deepEqual(result.cli.story.changed,['package.json']);
 assert.match(human,/UNKNOWN:.*declaredIntent: UNAVAILABLE/);
 assert.match(human,/UNKNOWN:.*conflictAssessment: INDETERMINATE/);
 assert.match(human,/Supporting evidence: CHANGED/);
 assert.match(human,/Changed paths: package\.json/);
 assert.match(human,/Whole-project currentness: NOT ESTABLISHED/);
 assert.match(human,/WHAT CHANGED: package\.json/);
 assert.match(human,/DRIFT:.*INDETERMINATE/);
 assert.equal(json.truth.refresh.changed[0],'package.json');
 assert.equal(json.cli.story.changed[0],'package.json');
 assert.equal(result.cli.story.semanticResultIdentity,result.truth.semanticResultIdentity);
 assert.equal(result.vscode.truthRef,result.truth.semanticResultIdentity);
 assert.equal(result.agent.truthRef,result.truth.semanticResultIdentity);
 assert.equal(result.cli.truthRef,result.truth.semanticResultIdentity);
 assert.equal(json.vscode.truthRef,result.truth.semanticResultIdentity);
 assert.equal(json.vscode.truth,undefined);
 assert.equal(result.cli.story.executionAuthority,false);
 const tests=['STORY_UNKNOWN_MATERIAL_DIMENSIONS_VISIBLE','STORY_UNKNOWN_NOT_COLLAPSED_TO_UNAVAILABLE_WHEN_DIMENSIONS_EXIST','STORY_CURRENT_ADAPTIVE_GAPS_PREFERRED_OVER_LEGACY_UNKNOWN_SET','STORY_SUPPORTING_REFRESH_CHANGE_VISIBLE','STORY_CHANGED_PATH_VISIBLE','STORY_BASE_README_UNCHANGED_DOES_NOT_HIDE_SUPPORTING_CHANGE','STORY_WHOLE_PROJECT_CURRENTNESS_NOT_INFERRED','STORY_CHANGED_FILE_NOT_DRIFT','STORY_JSON_HUMAN_CHANGE_PARITY'];
 console.log(JSON.stringify({status:'PASS',controls:tests.length,tests,changed:result.cli.story.changed,semanticResultIdentity:result.truth.semanticResultIdentity}));
})().catch(error=>{console.error(error.stack||error);process.exitCode=1;});
