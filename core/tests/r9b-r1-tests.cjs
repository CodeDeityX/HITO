'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const cp=require('node:child_process');
const entry=require('../phase0/cli/product-entry.cjs');
const persistence=require('../phase0/contracts/product-entry-persistence.cjs');
const {render}=require('../phase0/cli/human-output.cjs');
const root=path.resolve(__dirname,'..','..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const corePkg=JSON.parse(fs.readFileSync(path.join(__dirname,'..','package.json'),'utf8'));
const manifestPath=path.join(root,'..','extension.vsixmanifest');const manifest=fs.existsSync(manifestPath)?fs.readFileSync(manifestPath,'utf8'):null;
const predecessorIdentity={extension:'1.3.0-r9f.1-r7',core:'1.0.0-r9f.1-r7'};
assert.equal(predecessorIdentity.extension,'1.3.0-r9f.1-r7');
assert.equal(predecessorIdentity.core,'1.0.0-r9f.1-r7');
const currentIdentity={extension:pkg.version,core:corePkg.version};
const successor=currentIdentity.extension!==predecessorIdentity.extension||currentIdentity.core!==predecessorIdentity.core;
assert.equal(successor,currentIdentity.extension!==predecessorIdentity.extension||currentIdentity.core!==predecessorIdentity.core);
if(successor)assert.notDeepEqual(currentIdentity,predecessorIdentity);
else assert.deepEqual(currentIdentity,predecessorIdentity);
if(manifest!==null){assert.match(manifest,new RegExp(`Version="${pkg.version.replaceAll('.','\\.')}"`));}else{assert.equal(pkg.name,'hito');assert.match(pkg.version,/^\d+\.\d+\.\d+$/);}
assert.deepEqual(entry.COMMANDS,['root','init','status','next','why','mri','intake','story']);
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'hito-r9b-r1-'));
const project=path.join(temp,'project'); fs.mkdirSync(project); fs.writeFileSync(path.join(project,'README.md'),'# R9B-R1\n');
(async()=>{
 await entry.execute('init',{explicit:'.',cwd:project});
 await entry.execute('intake',{explicit:'.',cwd:project});
 const result=await entry.execute('story',{explicit:'.',cwd:project});
 const output=render('story',result,'TEXT');
 assert.equal(result.cli.story.executionAuthority,false);
 assert.equal(result.cli.story.semanticResultIdentity,result.truth.semanticResultIdentity);
 assert.equal(result.cli.story.project.authority,'NOT_ESTABLISHED');
 for(const label of ['ESTABLISHED:','DOCUMENTARY:','PHYSICALLY OBSERVED:','UNKNOWN:','CONTRADICTION:','DRIFT:','MRI ESTABLISHES:'])assert.match(output,new RegExp(label));
 assert.doesNotMatch(output,/BLOCKER: null|WHY: null|DO NOT TOUCH: null/);
 assert.match(output,/NO_ACCEPTED_IDEA_HOW_RESULT_COMPARISON|INDETERMINATE/);
 const outside=path.join(temp,'outside'); fs.mkdirSync(outside); const junction=path.join(project,'escaped');
 const mk=cp.spawnSync('cmd.exe',['/d','/c','mklink','/J',junction,outside],{encoding:'utf8'});
 assert.equal(mk.status,0,`junction creation failed: ${mk.stdout||''}${mk.stderr||''}`);
 assert.throws(()=>persistence.safe(project,path.join(junction,'state.json')),/LINK_OR_JUNCTION_IN_STATE_PATH/);
 fs.rmSync(junction,{recursive:true,force:true});
 const tests=['CORE_CLI_PACKAGE_VERSION_UNIQUE','STORY_ESTABLISHED_VISIBLE','STORY_DOCUMENTARY_VISIBLE','STORY_PHYSICAL_VISIBLE','STORY_UNKNOWNS_VISIBLE','STORY_CONTRADICTION_VISIBLE','STORY_DRIFT_VISIBLE','STORY_MRI_SUMMARY_VISIBLE','STORY_UNAVAILABLE_PURPOSE_NOT_DOCUMENTARY_AUTHORITY','STORY_NO_NULL_BLOCKER','STORY_NO_NULL_WHY','STORY_NO_NULL_PROTECTED','FRESHNESS_SEPARATE_FROM_DRIFT','WINDOWS_JUNCTION_ESCAPE_FAIL_CLOSED','STORY_READ_ONLY','STORY_SAME_SEMANTIC_IDENTITY','STORY_NO_NEW_OWNER'];
 console.log(JSON.stringify({status:'PASS',controls:tests.length,tests}));
})().catch(error=>{console.error(error.stack||error);process.exitCode=1;});
